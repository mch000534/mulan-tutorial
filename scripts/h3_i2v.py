#!/usr/bin/env python3
"""Generate image-to-video clips with a remote ComfyUI (MiniMax H3).

The workflow mirrors ComfyUI's official `video_minimax_h3_i2v` template
(flattened, API format) with the models installed on the server:

    diffusion_models/minimax_h3_fl2va_pruned_int8_convrot.safetensors
    text_encoders/qwen3vl_32b_minimax_h3_nvfp4_awq.safetensors
    vae/minimax_h3_video_vae_fp16.safetensors
    vae/minimax_h3_audio_vae_fp32.safetensors
    loras/minimax_h3_fl2v_turbo_8step_v1.0_comfyui_bf16.safetensors

The i2v prompts come verbatim from `design/02` §二十一 (45 鏡 i2v 提示詞);
the first frames are the stills already generated by `scripts/comfy_batch.py`.

Usage:
    python3 scripts/h3_i2v.py --shots 01,02,03 --aspect 16x9 --megapixels 0.4
    python3 scripts/h3_i2v.py --shots 01 --aspect 16x9 --megapixels 0.4 --force
    python3 scripts/h3_i2v.py --shots 15,25,43 --aspect 9x16 --megapixels 0.4
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import sys
import time
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from shotlist import (  # noqa: E402
    DOC_BOARD,
    i2v_length,
    parse_board,
    parse_i2v_prompts,
    parse_slow_motion,
)

MANIFEST = ROOT / "assets" / "video" / "manifest_i2v.jsonl"

UNET = "minimax_h3_fl2va_pruned_int8_convrot.safetensors"
CLIP = "qwen3vl_32b_minimax_h3_nvfp4_awq.safetensors"
VAE_VIDEO = "minimax_h3_video_vae_fp16.safetensors"
VAE_AUDIO = "minimax_h3_audio_vae_fp32.safetensors"
LORA_TURBO = "minimax_h3_fl2v_turbo_8step_v1.0_comfyui_bf16.safetensors"

H3_FPS = 24
BASE_STEPS = 20
TURBO_STEPS = 8


# --------------------------------------------------------------------------
# 畫幅與素材長度
# --------------------------------------------------------------------------


def ceil32(value: float) -> int:
    return int(math.ceil(value / 32.0) * 32)


def resolution(megapixels: float, aspect: str) -> tuple[int, int]:
    """H3 畫布：短邊對齊 32，長邊按比例（官方 ResolutionSelector 的算法）。"""
    pixels = megapixels * 1_000_000
    if aspect == "16x9":
        width = ceil32(math.sqrt(pixels * 16 / 9))
        height = ceil32(math.sqrt(pixels * 9 / 16))
    elif aspect == "9x16":
        width = ceil32(math.sqrt(pixels * 9 / 16))
        height = ceil32(math.sqrt(pixels * 16 / 9))
    else:
        raise ValueError(f"未知畫幅：{aspect}")
    return width, height


def frame_length(seconds: float) -> int:
    """H3 幀數：24fps，向上取到 17k+5 的模型網格（5, 22, 39 …）。"""
    length = max(5, int(round(seconds * H3_FPS)))
    return length + (5 - length % 17) % 17


# --------------------------------------------------------------------------
# ComfyUI
# --------------------------------------------------------------------------


def build_workflow(job: dict) -> dict:
    """Flatten the official `video_minimax_h3_i2v` template into API format."""
    wf = {
        "1": {"class_type": "UNETLoader", "inputs": {
            "unet_name": UNET, "weight_dtype": "default"}},
        "2": {"class_type": "CLIPLoader", "inputs": {
            "clip_name": CLIP, "type": "minimax", "device": "default"}},
        "3": {"class_type": "VAELoader", "inputs": {"vae_name": VAE_VIDEO}},
        "4": {"class_type": "VAELoader", "inputs": {"vae_name": VAE_AUDIO}},
        "5": {"class_type": "RandomNoise", "inputs": {"noise_seed": job["seed"]}},
        "6": {"class_type": "KSamplerSelect", "inputs": {"sampler_name": "res_multistep"}},
        "7": {"class_type": "BasicScheduler", "inputs": {
            "model": ["8", 0], "scheduler": "simple",
            "steps": job["steps"], "denoise": 1.0}},
        "8": {"class_type": "LoraLoaderModelOnly", "inputs": {
            "model": ["1", 0], "lora_name": LORA_TURBO, "strength_model": 1.0}},
        "9": {"class_type": "BasicGuider", "inputs": {
            "model": ["8", 0], "conditioning": ["10", 0]}},
        "10": {"class_type": "MiniMaxH3ImageToVideo", "inputs": {
            "clip": ["2", 0], "vae": ["3", 0], "prompt": job["prompt"],
            "width": job["width"], "height": job["height"], "length": job["length"],
            "first_frame": ["11", 0]}},
        "11": {"class_type": "LoadImage", "inputs": {"image": job["image"]}},
        "12": {"class_type": "SamplerCustomAdvanced", "inputs": {
            "noise": ["5", 0], "guider": ["9", 0], "sampler": ["6", 0],
            "sigmas": ["7", 0], "latent_image": ["10", 1]}},
        "13": {"class_type": "VAEDecode", "inputs": {
            "samples": ["12", 0], "vae": ["3", 0]}},
        "14": {"class_type": "VAEDecodeAudio", "inputs": {
            "samples": ["12", 0], "vae": ["4", 0]}},
        "15": {"class_type": "CreateVideo", "inputs": {
            "images": ["13", 0], "audio": ["14", 0], "fps": H3_FPS,
            "codec": "h264", "color_space": "sRGB", "bit_depth": 8}},
        "16": {"class_type": "SaveVideo", "inputs": {
            "video": ["15", 0], "filename_prefix": job["prefix"], "format": "mp4"}},
    }
    return wf


_upload_cache: dict[str, str] = {}


def upload_image(base: str, path: Path) -> str:
    key = str(path)
    if key in _upload_cache:
        return _upload_cache[key]
    data = path.read_bytes()
    digest = hashlib.sha1(data).hexdigest()[:10]
    ext = path.suffix
    name = f"mulan_h3_{digest}{ext}"
    mime = "image/jpeg" if ext.lower() in (".jpg", ".jpeg") else "image/png"
    r = requests.post(
        base + "/upload/image",
        files={"image": (name, data, mime)},
        data={"overwrite": "true", "type": "input"},
        timeout=120,
    )
    r.raise_for_status()
    info = r.json()
    uploaded = info["name"]
    if info.get("subfolder"):
        uploaded = info["subfolder"] + "/" + uploaded
    _upload_cache[key] = uploaded
    return uploaded


def submit(base: str, wf: dict) -> str:
    r = requests.post(base + "/prompt", json={"prompt": wf, "client_id": "mulan-h3"},
                      timeout=120)
    if r.status_code != 200:
        raise RuntimeError(f"prompt HTTP {r.status_code}: {r.text[:2000]}")
    data = r.json()
    if data.get("node_errors"):
        raise RuntimeError("node_errors: " + json.dumps(data["node_errors"], ensure_ascii=False)[:3000])
    if not data.get("prompt_id"):
        raise RuntimeError("no prompt_id: " + r.text[:2000])
    return data["prompt_id"]


def wait(base: str, pid: str, timeout: float = 3600) -> dict:
    start = time.time()
    while time.time() - start < timeout:
        try:
            r = requests.get(f"{base}/history/{pid}", timeout=30)
            r.raise_for_status()
            history = r.json()
        except Exception as e:  # noqa: BLE001
            print(f"    poll error: {e}", flush=True)
            time.sleep(3)
            continue
        if pid in history:
            return history[pid]
        time.sleep(2)
    raise TimeoutError(f"timeout waiting for {pid}")


def find_video(item: dict) -> dict:
    for node in item.get("outputs", {}).values():
        for key in ("video", "videos", "images"):
            entries = node.get(key)
            if not entries:
                continue
            if isinstance(entries, dict):
                entries = [entries]
            for entry in entries:
                if entry.get("filename"):
                    return entry
    raise RuntimeError("no video in outputs: "
                       + json.dumps(item.get("outputs"), ensure_ascii=False)[:1200])


def download(base: str, entry: dict, target: Path) -> Path:
    params = {
        "filename": entry["filename"],
        "subfolder": entry.get("subfolder", ""),
        "type": entry.get("type", "output"),
    }
    r = requests.get(base + "/view", params=params, timeout=300)
    r.raise_for_status()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(r.content)
    return target


def log_manifest(record: dict) -> None:
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    with open(MANIFEST, "a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")


# --------------------------------------------------------------------------
# 任務
# --------------------------------------------------------------------------


def load_jobs(args: argparse.Namespace) -> list[dict]:
    static, _motion, _scenes = parse_board(DOC_BOARD)
    i2v = parse_i2v_prompts(DOC_BOARD)
    slow = parse_slow_motion(DOC_BOARD)

    shots: list[int] = []
    for chunk in args.shots.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        shots.append(int(chunk))
    if not shots:
        shots = sorted(static)

    width, height = resolution(args.megapixels, args.aspect)
    suffix = "_16x9" if args.aspect == "16x9" else "_916"

    jobs = []
    for no in shots:
        shot = static.get(no)
        if shot is None:
            raise SystemExit(f"分鏡表沒有第 {no} 鏡")
        prompt = i2v.get(f"shot_{no:02d}", "")
        if not prompt:
            raise SystemExit(f"design/02 附錄沒有 shot_{no:02d} 的 i2v 提示詞")

        seconds = float(shot["seconds"])
        clip_seconds = args.seconds or i2v_length(seconds, slow.get(no))
        frame = ROOT / "assets" / "generated" / ("shots_16x9" if args.aspect == "16x9" else "shots") \
            / f"shot_{no:02d}{suffix}.jpg"
        if not frame.exists():
            raise SystemExit(f"找不到首幀：{frame}")

        stem = f"shot_{no:02d}{suffix}"
        if args.variant:
            stem += f"_{args.variant}"

        jobs.append({
            "id": stem,
            "shot": no,
            "variant": args.variant,
            "prompt": prompt,
            "first_frame": str(frame.relative_to(ROOT)),
            "width": width,
            "height": height,
            "length": frame_length(clip_seconds),
            "clip_seconds": clip_seconds,
            "steps": args.steps,
            "seed": args.seed + no * 137,
            "target": ROOT / "assets" / "video" / ("shots_169" if args.aspect == "16x9" else "shots_916") \
                / f"{stem}.mp4",
            "prefix": f"MULAN_H3/{stem}",
        })
    return jobs


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--base", default=os.environ.get("COMFY_BASE", "http://172.16.30.35:8188"))
    p.add_argument("--shots", default="01,02,03", help="鏡次，逗號分隔（01,02,03）")
    p.add_argument("--aspect", default="16x9", choices=["16x9", "9x16"])
    p.add_argument("--megapixels", type=float, default=0.4, help="畫布百萬像素（0.4 → 864x480）")
    p.add_argument("--seconds", type=float, default=0, help="素材秒數（0 = 依鏡長 ×2，最低 5 秒）")
    p.add_argument("--steps", type=int, default=TURBO_STEPS, help="採樣步數")
    p.add_argument("--seed", type=int, default=9100, help="隨機種子基準")
    p.add_argument("--variant", default="", help="版本標記（v2 = 第二輪不同 seed 的備選素材）")
    p.add_argument("--limit", type=int, default=0)
    p.add_argument("--force", action="store_true")
    p.add_argument("--stop-on-error", action="store_true")
    args = p.parse_args()

    jobs = load_jobs(args)
    if args.limit:
        jobs = jobs[: args.limit]

    print(f"comfy: {args.base}")
    print(f"jobs: {len(jobs)}  canvas: {jobs[0]['width']}x{jobs[0]['height']}  "
          f"steps: {args.steps}  frames: {jobs[0]['length']} ({(jobs[0]['length'] / H3_FPS):.2f}s)")
    done = 0
    for idx, job in enumerate(jobs, 1):
        target = job["target"]
        if target.exists() and target.stat().st_size > 10240 and not args.force:
            print(f"[{idx}/{len(jobs)}] skip {job['id']} (exists)", flush=True)
            done += 1
            continue
        print(f"[{idx}/{len(jobs)}] {job['id']} {job['width']}x{job['height']} "
              f"{job['length']}f seed={job['seed']} <- {job['first_frame']}", flush=True)
        t0 = time.time()
        try:
            image = upload_image(args.base, ROOT / job["first_frame"])
            wf = build_workflow({**job, "image": image})
            pid = submit(args.base, wf)
            item = wait(args.base, pid)
            status = item.get("status", {}).get("status_str", "?")
            if status != "success":
                raise RuntimeError("status=" + status + " " +
                                   json.dumps(item.get("status"), ensure_ascii=False)[:2000])
            download(args.base, find_video(item), target)
            dt = time.time() - t0
            print(f"    ok {dt:.1f}s -> {target.relative_to(ROOT)} "
                  f"({target.stat().st_size / 1024:.0f} KB)", flush=True)
            log_manifest({
                "shot_id": job["id"], "tool": "ComfyUI", "version": "0.37.4",
                "model": "MiniMax-H3", "variant": job.get("variant", ""),
                "seed": job["seed"], "prompt": job["prompt"],
                "duration_s": round(job["length"] / H3_FPS, 2),
                "clip_seconds": job["clip_seconds"], "aspect": args.aspect,
                "width": job["width"], "height": job["height"],
                "steps": job["steps"], "first_frame": job["first_frame"],
                "audio": f"{job['id']}.mp4 (原生立體聲)",
                "prompt_id": pid, "seconds": round(dt, 1), "result": "success",
            })
            done += 1
        except KeyboardInterrupt:
            print("interrupted", flush=True)
            break
        except Exception as e:  # noqa: BLE001
            print(f"    FAILED: {e}", flush=True)
            log_manifest({"shot_id": job["id"], "model": "MiniMax-H3", "seed": job["seed"],
                          "aspect": args.aspect, "result": "failed", "error": str(e)[:2000]})
            if args.stop_on_error:
                break
    print(f"finished {done}/{len(jobs)}", flush=True)


if __name__ == "__main__":
    main()
